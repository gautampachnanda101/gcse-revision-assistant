package main

// Subject packs: data/<name>.js files listed in subjects.js (the manifest).
//
// subjects.js is plain JavaScript so app.html can load it straight from disk, but its body is pure JSON:
//   window.REVISION_MANIFEST={...};
// The binary embeds the packs it was built with, and on start-up (when online) fetches the repo's current
// subjects.js, downloading any new or changed pack into the local cache after verifying its SHA-256.
// Offline, it serves whatever it already has — built-in packs plus previously downloaded ones.

import (
	"bytes"
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"net/http"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

const manifestPrefix = "window.REVISION_MANIFEST="

type subjectEntry struct {
	ID       string `json:"id"`
	Title    string `json:"title,omitempty"`
	Board    string `json:"board,omitempty"`
	Category string `json:"category,omitempty"`
	File     string `json:"file"`
	SHA256   string `json:"sha256"`
	Bytes    int    `json:"bytes,omitempty"`
}

type manifest struct {
	Schema   int            `json:"schema"`
	Subjects []subjectEntry `json:"subjects"`
}

var validPackFile = regexp.MustCompile(`^data/[A-Za-z0-9_-]+\.js$`)

func parseManifest(b []byte) (manifest, error) {
	var m manifest
	s := strings.TrimSpace(string(b))
	i := strings.Index(s, manifestPrefix)
	if i < 0 || strings.TrimSpace(stripLineComments(s[:i])) != "" {
		return m, errors.New("subjects.js: missing " + manifestPrefix + " prefix")
	}
	s = strings.TrimSuffix(strings.TrimSpace(s[i+len(manifestPrefix):]), ";")
	if err := json.Unmarshal([]byte(s), &m); err != nil {
		return m, fmt.Errorf("subjects.js: %w", err)
	}
	return m, nil
}

func renderManifest(m manifest) []byte {
	b, _ := json.MarshalIndent(m, "", " ")
	return []byte("// Generated by `gcse-revision manifest` — lists every subject pack under data/. Do not edit by hand.\n" +
		manifestPrefix + string(b) + ";\n")
}

func sha256Hex(b []byte) string {
	h := sha256.Sum256(b)
	return hex.EncodeToString(h[:])
}

func embeddedManifest() manifest {
	b, err := embedded.ReadFile("subjects.js")
	if err != nil {
		return manifest{Schema: 1}
	}
	m, err := parseManifest(b)
	if err != nil {
		return manifest{Schema: 1}
	}
	return m
}

func cacheManifestPath() string { return filepath.Join(dataDir(), "subjects.js") }
func cachePackPath(file string) string {
	return filepath.Join(dataDir(), filepath.FromSlash(file))
}

// packBytes returns a pack's contents if we hold a copy (cached or embedded) matching the given hash.
func packBytes(e subjectEntry) ([]byte, bool) {
	if !validPackFile.MatchString(e.File) {
		return nil, false
	}
	if b, err := os.ReadFile(cachePackPath(e.File)); err == nil && sha256Hex(b) == e.SHA256 {
		return b, true
	}
	if b, err := embedded.ReadFile(e.File); err == nil && sha256Hex(b) == e.SHA256 {
		return b, true
	}
	return nil, false
}

// effectiveManifest: the latest downloaded manifest's subjects that are actually available locally,
// followed by any built-in subject it doesn't mention. Works with no network at all.
func effectiveManifest() manifest {
	out := manifest{Schema: 1}
	seen := map[string]bool{}
	for _, e := range privatePacks() { // this computer's private packs win over published ones with the same id
		if !seen[e.ID] {
			out.Subjects = append(out.Subjects, e)
			seen[e.ID] = true
		}
	}
	if b, err := os.ReadFile(cacheManifestPath()); err == nil {
		if m, err := parseManifest(b); err == nil {
			for _, e := range m.Subjects {
				if _, ok := packBytes(e); ok && !seen[e.ID] {
					out.Subjects = append(out.Subjects, e)
					seen[e.ID] = true
				}
			}
		}
	}
	for _, e := range embeddedManifest().Subjects {
		if !seen[e.ID] {
			out.Subjects = append(out.Subjects, e)
			seen[e.ID] = true
		}
	}
	return out
}

// readSubjectFile serves data/<x>.js: the copy named in the effective manifest, else whatever exists.
func readSubjectFile(name string) ([]byte, error) {
	if strings.HasPrefix(name, "data/"+privatePrefix) {
		return readPrivatePack(name)
	}
	if !validPackFile.MatchString(name) {
		return nil, fs.ErrNotExist
	}
	for _, e := range effectiveManifest().Subjects {
		if e.File == name {
			if b, ok := packBytes(e); ok {
				return b, nil
			}
		}
	}
	if b, err := embedded.ReadFile(name); err == nil {
		return b, nil
	}
	return os.ReadFile(cachePackPath(name))
}

func rawURL(repo, branch, file string) string {
	base := envOr("GCSE_REVISION_RAW_BASE", "https://raw.githubusercontent.com") // override for testing/mirrors
	return strings.TrimRight(base, "/") + "/" + repo + "/" + branch + "/" + file
}

func httpGet(ctx context.Context, url string, limit int64) ([]byte, error) {
	req, err := http.NewRequestWithContext(ctx, http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}
	req.Header.Set("User-Agent", appName+"/"+version)
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", url, resp.Status)
	}
	return io.ReadAll(io.LimitReader(resp.Body, limit))
}

func writeFileAtomic(dst string, b []byte) error {
	if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
		return err
	}
	tmp := dst + ".tmp"
	if err := os.WriteFile(tmp, b, 0o644); err != nil {
		return err
	}
	return os.Rename(tmp, dst)
}

// syncSubjects downloads new/changed packs listed in the repo's subjects.js. Returns how many were fetched.
func syncSubjects(ctx context.Context, repo, branch string, log func(string, ...any)) (int, error) {
	if repo == "" || strings.Contains(repo, "OWNER") {
		return 0, errors.New("no source repo configured")
	}
	mb, err := httpGet(ctx, rawURL(repo, branch, "subjects.js"), 4<<20)
	if err != nil {
		return 0, err
	}
	sig, err := httpGet(ctx, rawURL(repo, branch, sigFile), 4<<10)
	if err != nil {
		return 0, fmt.Errorf("content signature: %w", err)
	}
	if err := verifyManifestSig(mb, sig); err != nil {
		return 0, err
	}
	remote, err := parseManifest(mb)
	if err != nil {
		return 0, err
	}
	fetched := 0
	for _, e := range remote.Subjects {
		if !validPackFile.MatchString(e.File) || len(e.SHA256) != 64 {
			log("Skipping invalid manifest entry %q", e.File)
			continue
		}
		if _, ok := packBytes(e); ok {
			continue
		}
		log("Downloading subject pack %s…", e.File)
		b, err := httpGet(ctx, rawURL(repo, branch, e.File), 64<<20)
		if err != nil {
			return fetched, err
		}
		if sha256Hex(b) != e.SHA256 {
			return fetched, fmt.Errorf("%s: checksum mismatch (repo mid-update? try again shortly)", e.File)
		}
		if err := writeFileAtomic(cachePackPath(e.File), b); err != nil {
			return fetched, err
		}
		fetched++
	}
	return fetched, writeFileAtomic(cacheManifestPath(), mb)
}

var (
	reStorageID   = regexp.MustCompile(`"storageId"\s*:\s*"([^"]+)"`)
	reBrandTitle  = regexp.MustCompile(`"brandTitle"\s*:\s*"([^"]+)"`)
	reExamBoard   = regexp.MustCompile(`"examBoard"\s*:\s*"([^"]+)"`)
	reSubjectArea = regexp.MustCompile(`"subjectArea"\s*:\s*"([^"]+)"`)
)

func firstMatch(re *regexp.Regexp, b []byte) string {
	if m := re.FindSubmatch(b); m != nil {
		return string(m[1])
	}
	return ""
}

// writeManifest regenerates <dir>/subjects.js from <dir>/data/*.js, keeping the existing order.
func writeManifest(dir string) error {
	files, err := filepath.Glob(filepath.Join(dir, "data", "*.js"))
	if err != nil {
		return err
	}
	order := map[string]int{}
	if b, err := os.ReadFile(filepath.Join(dir, "subjects.js")); err == nil {
		if m, err := parseManifest(b); err == nil {
			for i, e := range m.Subjects {
				order[e.File] = i
			}
		}
	}
	var out manifest
	out.Schema = 1
	ids := map[string]string{}
	for _, f := range files {
		b, err := os.ReadFile(f)
		if err != nil {
			return err
		}
		rel := path.Join("data", filepath.Base(f))
		if !validPackFile.MatchString(rel) {
			return fmt.Errorf("%s: pack file names may only use letters, digits, - and _", rel)
		}
		if !bytes.Contains(b, []byte("REVISION_SUBJECTS")) {
			return fmt.Errorf("%s: doesn't push onto window.REVISION_SUBJECTS", rel)
		}
		id := firstMatch(reStorageID, b)
		if id == "" {
			return fmt.Errorf("%s: config.storageId is required", rel)
		}
		if other, dup := ids[id]; dup {
			return fmt.Errorf("%s and %s share storageId %q", other, rel, id)
		}
		ids[id] = rel
		out.Subjects = append(out.Subjects, subjectEntry{
			ID: id, Title: firstMatch(reBrandTitle, b), Board: firstMatch(reExamBoard, b),
			Category: firstMatch(reSubjectArea, b), File: rel, SHA256: sha256Hex(b), Bytes: len(b),
		})
	}
	sort.SliceStable(out.Subjects, func(i, j int) bool {
		oi, iok := order[out.Subjects[i].File]
		oj, jok := order[out.Subjects[j].File]
		switch {
		case iok && jok:
			return oi < oj
		case iok != jok:
			return iok
		default:
			return out.Subjects[i].File < out.Subjects[j].File
		}
	})
	if err := os.WriteFile(filepath.Join(dir, "subjects.js"), renderManifest(out), 0o644); err != nil {
		return err
	}
	fmt.Printf("Wrote subjects.js with %d subject pack(s).\n", len(out.Subjects))
	return nil
}

func stripLineComments(s string) string {
	var out []string
	for _, l := range strings.Split(s, "\n") {
		if !strings.HasPrefix(strings.TrimSpace(l), "//") {
			out = append(out, l)
		}
	}
	return strings.Join(out, "\n")
}
